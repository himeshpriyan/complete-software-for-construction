export const DEFAULT_PERMISSION_MAP: Record<UserRole, Record<string, Record<PermissionAction, boolean>>> = (() => {
  const roles: UserRole[] = [
    'super_admin',
    'management',
    'project_manager',
    'site_engineer',
    'civil_engineer',
    'purchase_manager',
    'store_manager',
    'accounts',
    'hr',
    'sales',
    'estimation_engineer',
    'qs',
    'safety_officer',
    'client',
    'subcontractor',
    'admin',
  ];

  const map: Record<string, Record<string, Record<PermissionAction, boolean>>> = {};

  roles.forEach((r) => {
    map[r] = {};
    PERMISSION_MODULES.forEach((m) => {
      if (r === 'super_admin' || r === 'admin') {
        map[r][m.id] = { create: true, view: true, edit: true, delete: true, approve: true, export: true, download: true };
      } else if (r === 'management') {
        map[r][m.id] = { create: false, view: true, edit: false, delete: false, approve: true, export: true, download: true };
      } else if (r === 'project_manager') {
        const isCore = ['projects', 'tasks', 'dpr', 'estimation', 'safety', 'quality', 'procurement', 'contracts', 'documents'].includes(m.id);
        map[r][m.id] = { create: isCore, view: true, edit: isCore, delete: false, approve: isCore, export: true, download: true };
      } else if (r === 'site_engineer') {
        const isSite = ['dpr', 'tasks', 'safety', 'quality', 'equipment', 'labour'].includes(m.id);
        map[r][m.id] = { create: isSite, view: ['projects', 'dpr', 'tasks', 'safety', 'quality', 'documents', 'inventory'].includes(m.id), edit: isSite, delete: false, approve: false, export: false, download: true };
      } else if (r === 'accounts') {
        const isFin = ['billing', 'accounts', 'procurement', 'reports'].includes(m.id);
        map[r][m.id] = { create: isFin, view: isFin || m.id === 'projects', edit: isFin, delete: false, approve: isFin, export: true, download: true };
      } else if (r === 'purchase_manager') {
        const isProc = ['procurement', 'inventory', 'vendors'].includes(m.id);
        map[r][m.id] = { create: isProc, view: isProc || m.id === 'projects', edit: isProc, delete: false, approve: isProc, export: true, download: true };
      } else if (r === 'safety_officer') {
        const isHse = ['safety', 'quality', 'labour'].includes(m.id);
        map[r][m.id] = { create: isHse, view: isHse || m.id === 'projects' || m.id === 'dpr', edit: isHse, delete: false, approve: isHse, export: true, download: true };
      } else if (r === 'client') {
        const isClient = ['projects', 'billing', 'documents'].includes(m.id);
        map[r][m.id] = { create: false, view: isClient, edit: false, delete: false, approve: false, export: false, download: isClient };
      } else {
        map[r][m.id] = { create: false, view: ['projects', 'tasks', 'documents'].includes(m.id), edit: false, delete: false, approve: false, export: false, download: false };
      }
    });
  });

  return map as Record<UserRole, Record<string, Record<PermissionAction, boolean>>>;
})();

